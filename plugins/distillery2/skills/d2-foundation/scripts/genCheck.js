#!/usr/bin/env node
'use strict';
/**
 * genCheck.js — 機械チェックの一括実行 scripts/check.mjs と、コミットのときの hook .githooks/commit-msg を生成する (0.3.0)
 *
 *   node genCheck.js [--cwd <repo>] [--config .distillery/config.yaml] [--check]
 *
 * 観点は 6 つ: generate (生成物の鮮度) / format / lint / build / test / security。リポ全体 (文書類・設定) とティアごと (ソース) に当てる。
 * コマンドは config (genConfig が機械チェックの ADR から作る) と、生成物の表 (d2-common/scripts/lib/generators.js) から埋め込む。
 * 生成した check.mjs は依存なし (node だけ): `node scripts/check.mjs --mode ci|hook [--only <観点>]`
 *   ci   : 全ティア・全観点 (test は単体・契約・UC のシナリオ・受入、security は依存の脆弱性と SAST と秘密情報)
 *   hook : コミットするファイルに関わるものだけ (変えたティアの format・lint・build・単体テスト、文書類の format・lint、生成物の鮮度、秘密情報)
 * hook は .githooks/commit-msg から呼ぶ。d2-run の commit (件名が impl( / req( / req: / decide: / foundation: / precheck( / feedback: / feedback( か、
 * trailer に UC-Slug: がある main マージの squash) は回さない (d2-run は runGates で記録付きのゲートを回す。scaffold の red の commit を止めない)。
 * hook は git config core.hooksPath .githooks で入れる (このスクリプトが回す。clone した人はルートの package.json の prepare で入る)。
 * generate が使う distillery2 のスクリプトの場所: 環境変数 D2_SKILLS → インストール済みのプラグイン → (ci) .distillery/distillery2.lock.json の
 * repo と commit を .distillery/logs/d2-plugin/<commit> に取る。どれも無ければ ci は落ち、hook は「確かめられない」と出して通す。
 * --check: 書かずに、生成物 (check.mjs と commit-msg) が今の config と違えば exit 1。.distillery/distillery2.lock.json は比べない (プラグインの版で変わる)
 */
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { parseYaml } = require('../../d2-common/scripts/lib/yaml');
const { GENERATORS } = require('../../d2-common/scripts/lib/generators');
const { passWithNoTests, stripReport, ciCucumber } = require('./genCi');

const SKILLS_ROOT = path.resolve(__dirname, '..', '..');
const PLUGIN_REPO = 'https://github.com/suwa-sh/suwa-sh-claude-plugins.git';
const PLUGIN_PATH = 'plugins/distillery2/skills';
const D2_SUBJECTS = ['impl(', 'req(', 'req: ', 'decide: ', 'foundation: ', 'precheck(', 'feedback: ', 'feedback('];

function parseArgs(argv) {
  const o = { cwd: process.cwd(), config: '.distillery/config.yaml', check: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--cwd') o.cwd = path.resolve(argv[++i]);
    else if (a === '--config') o.config = argv[++i];
    else if (a === '--check') o.check = true;
    else throw new Error(`Unknown arg: ${a}`);
  }
  return o;
}

/** config から一括チェックの計画 (check.mjs に埋め込む JSON) を作る */
function buildPlan(config) {
  const cmds = config.commands || {};
  const providers = new Set((config.contracts || []).map((c) => c.provider).filter(Boolean));
  const tiers = (config.tiers || []).map((t) => {
    const c = t.commands || {};
    const dir = String(t.dir || `apps/${t.id}`).replace(/\/$/, '');
    const provider = providers.has(t.id) || (t.provides || []).length > 0;
    return {
      id: t.id, dir,
      format: c.format_check ? stripReport(c.format_check) : null,
      lint: c.lint ? stripReport(c.lint) : null,
      build: c.build ? stripReport(c.build) : (c.typecheck ? stripReport(c.typecheck) : null),
      unit: c.unit ? passWithNoTests(stripReport(c.unit)) : null,
      contract: provider && c.contract ? passWithNoTests(stripReport(c.contract)) : null,
      security: c.security ? stripReport(c.security) : null,
    };
  });
  const acceptance = [cmds.acceptance_api ? ciCucumber(cmds.acceptance_api, '@acceptance and not @browser') : 'npx cucumber-js --tags "@acceptance and not @browser"'];
  if (config.capabilities && config.capabilities.browser) acceptance.push(cmds.acceptance_browser ? ciCucumber(cmds.acceptance_browser, '@acceptance and @browser') : 'npx cucumber-js --tags "@acceptance and @browser"');
  return {
    tiers,
    repo: { format: cmds.format || null, lint: cmds.quality || null, arch_test: cmds.arch_test ? stripReport(cmds.arch_test) : null, secrets: cmds.secrets || null },
    scenarios: { uc_bdd: cmds.uc_bdd ? ciCucumber(cmds.uc_bdd, 'not @browser') : 'npx cucumber-js --tags "not @browser"', acceptance },
    // ルートの設定と共有パッケージを変えたら全ティア
    all_tiers_on: ['^packages/', '^package(-lock)?\\.json$', '^tsconfig\\.base\\.json$', '^biome\\.json$'],
    generators: GENERATORS.map((g) => ({ id: g.id, inputs: g.inputs.map((r) => r.source), outputs: g.outputs.map((r) => r.source), needs: g.needs || null, check: g.check })),
    plugin: { repo: PLUGIN_REPO, path: PLUGIN_PATH },
  };
}

const HEADER = '// generated by distillery2 genCheck.js — 生成物。手で直さない (.distillery/config.yaml と機械チェックの ADR から作り直す)';

/** check.mjs の本文 (依存なし。node 18 以上) */
function renderCheck(plan) {
  return `#!/usr/bin/env node
${HEADER}
// 機械チェックの一括実行: node scripts/check.mjs --mode ci|hook [--only generate|format|lint|build|test|security]
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const PLAN = ${JSON.stringify(plan, null, 2)};
const ASPECTS = ['generate', 'format', 'lint', 'build', 'test', 'security'];

const args = process.argv.slice(2);
const opt = (k) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : null; };
const mode = opt('--mode') || 'ci';
const only = opt('--only');
if (!['ci', 'hook'].includes(mode)) { console.error('--mode は ci か hook'); process.exit(2); }
if (only && !ASPECTS.includes(only)) { console.error(\`--only は \${ASPECTS.join(' / ')}\`); process.exit(2); }
const root = spawnSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf8' }).stdout.trim() || process.cwd();
process.chdir(root);

const q = (s) => \`'\${String(s).replace(/'/g, \`'\\\\''\`)}'\`;
const results = [];
function step(aspect, name, cmd, { skip = null } = {}) {
  if (only && aspect !== only) return;
  if (skip) { results.push({ aspect, name, status: 'skip', note: skip }); console.log(\`[\${aspect}] \${name}: skip (\${skip})\`); return; }
  console.log(\`[\${aspect}] \${name}: \${cmd}\`);
  const r = spawnSync(cmd, { shell: true, stdio: 'inherit', env: process.env });
  const ok = r.status === 0;
  results.push({ aspect, name, status: ok ? 'pass' : 'fail' });
  if (!ok) console.log(\`[\${aspect}] \${name}: FAIL (exit \${r.status})\`);
}

// コミットするファイル (hook)。ci は全部
const staged = mode === 'hook'
  ? spawnSync('git', ['diff', '--cached', '--name-only', '--diff-filter=ACMRD', '-z'], { encoding: 'utf8' }).stdout.split('\\0').filter(Boolean)
  : null;
const present = staged ? staged.filter((f) => fs.existsSync(f)) : null;
if (mode === 'hook' && !staged.length) { console.log('コミットするファイルが無い'); process.exit(0); }
const allTiers = !staged || staged.some((f) => PLAN.all_tiers_on.some((re) => new RegExp(re).test(f)));
const tiers = PLAN.tiers.filter((t) => allTiers || staged.some((f) => f === t.dir || f.startsWith(\`\${t.dir}/\`)));
const inTier = (f) => PLAN.tiers.some((t) => f.startsWith(\`\${t.dir}/\`));
const repoFiles = present ? present.filter((f) => !inTier(f)) : null;
const forFiles = (cmd, files) => \`\${cmd.replace(/\\s--all\\b/, '')} \${files.map(q).join(' ')}\`;

// generate: 生成物の鮮度。distillery2 のスクリプトの場所を探す
function findSkills() {
  if (process.env.D2_SKILLS && fs.existsSync(process.env.D2_SKILLS)) return process.env.D2_SKILLS;
  try {
    const ip = JSON.parse(fs.readFileSync(path.join(os.homedir(), '.claude', 'plugins', 'installed_plugins.json'), 'utf8'));
    for (const [k, v] of Object.entries(ip.plugins || {})) {
      if (!k.startsWith('distillery2@')) continue;
      const p = path.join((Array.isArray(v) ? v[0] : v).installPath, 'skills');
      if (fs.existsSync(p)) return p;
    }
  } catch {}
  if (mode !== 'ci') return null;
  let lock = null;
  try { lock = JSON.parse(fs.readFileSync('.distillery/distillery2.lock.json', 'utf8')); } catch {}
  if (!lock || !lock.commit) return null;
  const dir = path.join('.distillery', 'logs', 'd2-plugin', lock.commit);
  if (!fs.existsSync(path.join(dir, lock.path || PLAN.plugin.path))) {
    fs.mkdirSync(dir, { recursive: true });
    const g = (a) => spawnSync('git', a, { cwd: dir, stdio: 'inherit' }).status === 0;
    if (!(g(['init', '-q']) && g(['fetch', '-q', '--depth', '1', lock.repo || PLAN.plugin.repo, lock.commit]) && g(['checkout', '-q', 'FETCH_HEAD']))) return null;
  }
  return path.resolve(dir, lock.path || PLAN.plugin.path);
}
if (!only || only === 'generate') {
  const touched = PLAN.generators.filter((g) => !staged || staged.some((f) => [...g.inputs, ...g.outputs].some((re) => new RegExp(re).test(f))));
  const runnable = touched.filter((g) => !g.needs || fs.existsSync(g.needs));
  const skills = runnable.length ? findSkills() : null;
  for (const g of runnable) {
    if (!skills) { mode === 'ci' ? results.push({ aspect: 'generate', name: g.id, status: 'fail', note: 'distillery2 のスクリプトが無い' }) : null; console.log(\`[generate] \${g.id}: \${mode === 'ci' ? 'FAIL' : 'skip'} (distillery2 のスクリプトが見つからない。D2_SKILLS で場所を渡す)\`); continue; }
    for (const c of g.check) step('generate', g.id, ['node', ...c.map((a) => a.replace('<skills>', skills))].map(q).join(' '));
  }
}

// format / lint: リポ全体 (文書類・設定) とティアごと (ソース)
if (PLAN.repo.format) step('format', 'repo', PLAN.repo.format, { skip: repoFiles && !repoFiles.length ? 'リポ全体のファイルの変更なし' : null });
for (const t of tiers) if (t.format) step('format', t.id, t.format);
if (PLAN.repo.lint) step('lint', 'repo', repoFiles ? forFiles(PLAN.repo.lint, repoFiles) : PLAN.repo.lint, { skip: repoFiles && !repoFiles.length ? 'リポ全体のファイルの変更なし' : null });
if (PLAN.repo.arch_test) step('lint', 'arch', PLAN.repo.arch_test, { skip: staged && !tiers.length ? 'ティアの変更なし' : null });
for (const t of tiers) if (t.lint) step('lint', t.id, t.lint);
// build
for (const t of tiers) if (t.build) step('build', t.id, t.build);
// test: hook は単体だけ
for (const t of tiers) if (t.unit) step('test', \`\${t.id} unit\`, t.unit);
if (mode === 'ci') {
  for (const t of tiers) if (t.contract) step('test', \`\${t.id} contract\`, t.contract);
  step('test', 'uc-bdd', PLAN.scenarios.uc_bdd);
  PLAN.scenarios.acceptance.forEach((c, i) => step('test', \`acceptance\${i ? \` \${i + 1}\` : ''}\`, c));
}
// security: 秘密情報はリポ全体 (hook はコミットするファイル)、依存の脆弱性と SAST はティアごと (ci だけ)
if (PLAN.repo.secrets) step('security', 'secrets', present ? forFiles(PLAN.repo.secrets, present) : PLAN.repo.secrets, { skip: present && !present.length ? 'ファイルの追加・変更なし' : null });
if (mode === 'ci') for (const t of tiers) if (t.security) step('security', t.id, t.security);

const failed = results.filter((r) => r.status === 'fail');
console.log(\`\\n機械チェック (\${mode}\${only ? \` --only \${only}\` : ''}): \${results.filter((r) => r.status === 'pass').length} pass / \${failed.length} fail / \${results.filter((r) => r.status === 'skip').length} skip\`);
for (const f of failed) console.log(\`  FAIL [\${f.aspect}] \${f.name}\${f.note ? \` — \${f.note}\` : ''}\`);
process.exit(failed.length ? 1 : 0);
`;
}

/** commit-msg の hook (sh) */
function renderHook() {
  const cases = D2_SUBJECTS.map((s) => `"${s}"*`).join('|');
  return `#!/bin/sh
# generated by distillery2 genCheck.js — 生成物。手で直さない
# コミットのときの機械チェック (node scripts/check.mjs --mode hook)。
# d2-run の commit (件名の形か、main マージの squash の trailer UC-Slug:) は回さない: d2-run は記録付きのゲートを自分で回す
subject=$(head -n 1 "$1")
case "$subject" in
  ${cases}) exit 0 ;;
esac
if grep -q '^UC-Slug: ' "$1"; then exit 0; fi
exec node scripts/check.mjs --mode hook
`;
}

/** プラグインの commit (CI が generate のために取る)。リポの作業ツリーなら HEAD、インストール済みなら gitCommitSha */
function pluginCommit() {
  const r = spawnSync('git', ['rev-parse', 'HEAD'], { cwd: SKILLS_ROOT, encoding: 'utf8' });
  const top = spawnSync('git', ['rev-parse', '--show-toplevel'], { cwd: SKILLS_ROOT, encoding: 'utf8' });
  if (r.status === 0 && top.status === 0 && path.resolve(top.stdout.trim(), PLUGIN_PATH) === SKILLS_ROOT) return r.stdout.trim();
  try {
    const ip = JSON.parse(fs.readFileSync(path.join(os.homedir(), '.claude', 'plugins', 'installed_plugins.json'), 'utf8'));
    for (const [k, v] of Object.entries(ip.plugins || {})) {
      const e = Array.isArray(v) ? v[0] : v;
      if (k.startsWith('distillery2@') && SKILLS_ROOT.startsWith(path.resolve(e.installPath))) return e.gitCommitSha || null;
    }
  } catch {}
  return null;
}

function run(o) {
  const configPath = path.resolve(o.cwd, o.config);
  if (!fs.existsSync(configPath)) return { code: 2, error: `config not found: ${configPath}` };
  const plan = buildPlan(parseYaml(fs.readFileSync(configPath, 'utf8')) || {});
  const files = { 'scripts/check.mjs': renderCheck(plan), '.githooks/commit-msg': renderHook() };
  if (o.check) {
    const stale = Object.entries(files).filter(([rel, text]) => { const f = path.join(o.cwd, rel); return !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== text; }).map(([rel]) => rel);
    return { code: stale.length ? 1 : 0, stale };
  }
  for (const [rel, text] of Object.entries(files)) {
    const f = path.join(o.cwd, rel);
    fs.mkdirSync(path.dirname(f), { recursive: true });
    fs.writeFileSync(f, text);
    fs.chmodSync(f, 0o755);
  }
  const lock = { repo: PLUGIN_REPO, path: PLUGIN_PATH, commit: pluginCommit() };
  fs.mkdirSync(path.join(o.cwd, '.distillery'), { recursive: true });
  fs.writeFileSync(path.join(o.cwd, '.distillery', 'distillery2.lock.json'), JSON.stringify(lock, null, 2) + '\n');
  // コミットのときの hook を入れる (必須。git のリポでなければ何もしない)
  const inGit = spawnSync('git', ['rev-parse', '--git-dir'], { cwd: o.cwd }).status === 0;
  if (inGit) spawnSync('git', ['config', 'core.hooksPath', '.githooks'], { cwd: o.cwd });
  return { code: 0, written: Object.keys(files), hooks_path: inGit ? '.githooks' : null, plugin_commit: lock.commit };
}

function main(argv) {
  let o; try { o = parseArgs(argv); } catch (e) { console.error(e.message); return 2; }
  const r = run(o);
  if (r.error) { console.error(r.error); return r.code; }
  if (o.check) console.log(`genCheck --check: ${r.stale.length ? `STALE ${r.stale.join(', ')}` : 'up to date'}`);
  else console.log(`genCheck: → ${r.written.join(', ')} (core.hooksPath: ${r.hooks_path || 'git でない'})`);
  return r.code;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));
module.exports = { parseArgs, buildPlan, renderCheck, renderHook, run, D2_SUBJECTS };
