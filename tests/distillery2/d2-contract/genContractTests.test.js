'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { SCRIPTS, CONFIG, freshContracts, outRoot } = require('./support');

const compileContracts = require(path.join(SCRIPTS, 'compileContracts.js'));
const genContractTests = require(path.join(SCRIPTS, 'genContractTests.js'));
const contractGraph = require(path.join(SCRIPTS, 'lib/contractGraph.js'));

function generated(uc) {
  const { contractsDir } = freshContracts();
  compileContracts.run(contractsDir);
  const out = outRoot();
  genContractTests.run(contractsDir, { configPath: CONFIG, outRoot: out, uc });
  return out;
}
const read = (out, rel) => fs.readFileSync(path.join(out, rel), 'utf8');

test('provider テスト・consumer stub のファイル名が期待どおり', () => {
  const out = generated();
  const files = [];
  (function walk(d) { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); e.isDirectory() ? walk(p) : files.push(path.relative(out, p)); } })(out);
  const set = new Set(files);
  for (const f of [
    'apps/backend-api/test/contract/createLoan.test.ts',
    'apps/backend-api/test/contract/getBook.test.ts',
    'apps/backend-api/test/contract/returnLoan.test.ts',
    'apps/backend-api/test/contract/messages.test.ts',
    'packages/contracts/api/stubs/createLoan.201.json',
    'packages/contracts/api/stubs/createLoan.409.json',
    'packages/contracts/api/stubs/getBook.200.json',
    'packages/contracts/events/validators.ts',
    // 消費側 API クライアント (genApiClient 経由)
    'packages/contracts/api/types.ts',
    'packages/contracts/api/client.ts',
    'packages/contracts/api/server.ts',
  ]) assert.ok(set.has(f), `missing ${f}`);
});

