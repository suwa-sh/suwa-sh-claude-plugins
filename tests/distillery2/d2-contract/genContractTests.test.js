test('全生成では旧 operation の生成テストを stale として削除する', () => {
  const { contractsDir } = freshContracts();
  compileContracts.run(contractsDir);
  const out = outRoot();
  genContractTests.run(contractsDir, { configPath: CONFIG, outRoot: out });
  // 旧 operation を模した所有ファイル (OWNER_TAG 付き) を植える
  const orphan = path.join(out, 'apps/backend-api/test/contract/oldOp.test.ts');
  fs.writeFileSync(orphan, '// generated by distillery2 — do not edit\n// distillery2-owner: d2-contract/genContractTests\n');
  // genRdbDdl 由来の db-schema.test.ts (OWNER_TAG 無し) は消してはならない
  const foreign = path.join(out, 'apps/backend-api/test/contract/db-schema.test.ts');
  fs.writeFileSync(foreign, '// generated by distillery2 — do not edit\n');
  const r = genContractTests.run(contractsDir, { configPath: CONFIG, outRoot: out });
  assert.ok(!fs.existsSync(orphan), 'orphan test should be removed');
  assert.ok(r.removed.includes('apps/backend-api/test/contract/oldOp.test.ts'), 'removed should list orphan');
  assert.ok(fs.existsSync(foreign), 'foreign generated file must survive');
});

