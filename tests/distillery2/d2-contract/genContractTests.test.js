test('example の無い operation は it.todo になる', () => {
  const out = generated();
  const returnLoan = read(out, 'apps/backend-api/test/contract/returnLoan.test.ts');
  assert.match(returnLoan, /it\.todo\('responds 200/);
  const createLoan = read(out, 'apps/backend-api/test/contract/createLoan.test.ts');
  assert.match(createLoan, /it\('responds 201 \(example: success\)/);
  assert.match(createLoan, /it\('responds 409 \(example: conflict\)/);
  assert.doesNotMatch(createLoan, /it\.todo/);
});

test('status ごとに同名の request example を送る (201=success, 409=conflict)', () => {
  const out = generated();
  const createLoan = read(out, 'apps/backend-api/test/contract/createLoan.test.ts');
  // 201 は success 入力 (book-1)、409 は conflict 入力 (book-2) を送る
  const send201 = /responds 201 \(example: success\)[\s\S]*?\.send\((\{[^;]*?\})\)/.exec(createLoan);
  const send409 = /responds 409 \(example: conflict\)[\s\S]*?\.send\((\{[^;]*?\})\)/.exec(createLoan);
  assert.ok(send201 && /book-1/.test(send201[1]), 'expected 201 to send book-1 request');
  assert.ok(send409 && /book-2/.test(send409[1]), 'expected 409 to send book-2 request');
});

test('response example に対応する request example が無い status は it.todo', () => {
  // createLoan の 409 response example と同名の request example (conflict) を消すと todo になる
  const { contractsDir } = freshContracts();
  const openapiPath = path.join(contractsDir, 'openapi', 'openapi.yaml');
  const y = fs.readFileSync(openapiPath, 'utf8').replace(/              conflict:\n                value:\n                  bookId: book-2\n                  days: 14\n/, '');
  fs.writeFileSync(openapiPath, y);
  compileContracts.run(contractsDir);
  const out = outRoot();
  genContractTests.run(contractsDir, { configPath: CONFIG, outRoot: out });
  const createLoan = read(out, 'apps/backend-api/test/contract/createLoan.test.ts');
  assert.match(createLoan, /it\.todo\('409: request example "conflict" missing/);
});

test('生成物は do-not-edit ヘッダを持ち、決定論的', () => {
  const a = generated(), b = generated();
  const rel = 'apps/backend-api/test/contract/createLoan.test.ts';
  assert.match(read(a, rel), /generated by distillery2 — do not edit/);
  // 生成した .ts は biome の整形・lint を抑止する (埋め込み JSON を biome が展開して format_check が落ちた。0.1.10 実走 ④-2)
  assert.match(read(a, rel), /^\/\/ biome-ignore-all format: generated/m);
  assert.match(read(a, rel), /^\/\/ biome-ignore-all lint: generated/m);
  assert.equal(read(a, rel), read(b, rel));
});

